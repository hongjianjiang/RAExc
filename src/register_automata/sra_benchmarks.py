def get_xml_parser_sra():
    """Port of getXMLParserSRA: 3-letter tag."""
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(4)]
    T = [
        _store(curr, 0, 1, _eq(curr, "<"), 3),
        _store(curr, 1, 2, ALPHA(curr), 0),
        _store(curr, 2, 3, ALPHA(curr), 1),
        _store(curr, 3, 4, ALPHA(curr), 2),
        _store(curr, 2, 5, _eq(curr, ">"), 3),
        _store(curr, 3, 5, _eq(curr, ">"), 3),
        _store(curr, 4, 5, _eq(curr, ">"), 3),
        _store(curr, 5, 5, ALPHA_NUM(curr), 3),
        _store(curr, 5, 6, _eq(curr, "<"), 3),
        _store(curr, 6, 7, _eq(curr, "/"), 3),
        _check(curr, 7, 8, ALPHA(curr), 0, reg_vars),
        _check(curr, 8, 9, ALPHA(curr), 1, reg_vars),
        _check(curr, 9, 10, ALPHA(curr), 2, reg_vars),
        _store(curr, 8, 11, _eq(curr, ">"), 3),
        _store(curr, 9, 11, _eq(curr, ">"), 3),
        _store(curr, 10, 11, _eq(curr, ">"), 3),
    ]
    return RegisterAutomata(12, T, reg_vars, [11])


def get_small_xml_parser_sra():
    """Port of getSmallXMLParserSRA: 1- or 2-letter tag.

    Upstream preloads registers 0/1/2 with the constants '<', '>', '/' and
    only ever reads them via SRACheckMove -- since our RegisterAutomata
    always initializes registers to 0, a constant-valued register that is
    never overwritten is behaviorally identical to inlining the literal
    comparison, which is what's done here (registers 0/1 hold the tag
    letters, 2 is the garbage/dummy register).
    """
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(3)]
    garbage = 2
    T = [
        Transition(curr, 0, _eq(curr, "<"), {}, 1),
        _store(curr, 1, 2, ALPHA(curr), 0),
        _store(curr, 2, 3, ALPHA(curr), 1),
        Transition(curr, 2, _eq(curr, ">"), {}, 5),
        Transition(curr, 3, _eq(curr, ">"), {}, 5),
        Transition(curr, 4, _eq(curr, ">"), {}, 5),  # unreachable: no transition ever enters state 4 (upstream artifact)
        _store(curr, 5, 5, ALPHA_NUM(curr), garbage),
        Transition(curr, 5, _eq(curr, "<"), {}, 6),
        Transition(curr, 6, _eq(curr, "/"), {}, 7),
        _check(curr, 7, 8, ALPHA(curr), 0, reg_vars),
        _check(curr, 8, 9, ALPHA(curr), 1, reg_vars),
        Transition(curr, 8, _eq(curr, ">"), {}, 11),
        Transition(curr, 9, _eq(curr, ">"), {}, 11),
        Transition(curr, 10, _eq(curr, ">"), {}, 11),  # unreachable: state 10 is never entered (upstream artifact)
    ]
    return RegisterAutomata(12, T, reg_vars, [11])


# ---------------------------------------------------------------------------
# IPn PacketParser family: "srcip:D.D.D.D prt:D+ dstip:D.D.D.D prt:D+ pload:'AN+'"
# IPn checks that the first n digits (read left-to-right across octets,
# dots never counted) of the dst IP match the src IP. n in {2,3,4,6,9}.
# The "Simplified" variant drops the two "prt:" fields, uses "s:"/" d:"/" p:"
# instead of "srcip:"/" dstip:"/" prt:", and allows an optional run of
# ':'/alphanumeric junk after each IP instead of a numeric port.
# ---------------------------------------------------------------------------

def _emit_ipv4_octets(transitions, curr, state, reg_vars, dummy, n, mode):
    """4 dot-separated 3-digit octets. Digit position p (0-indexed across all
    12 digits) is a Store into reg[p] if mode=='store' and p<n, a Check
    against reg[p] if mode=='check' and p<n, and a plain dummy Store
    otherwise. Dots are always a dummy Store, in every variant."""
    for octet in range(4):
        for digit in range(3):
            pos = octet * 3 + digit
            if pos < n:
                if mode == "store":
                    transitions.append(_store(curr, state, state + 1, NUM(curr), pos))
                else:
                    transitions.append(_check(curr, state, state + 1, NUM(curr), pos, reg_vars))
            else:
                transitions.append(_store(curr, state, state + 1, NUM(curr), dummy))
            state += 1
        if octet < 3:
            transitions.append(_store(curr, state, state + 1, _eq(curr, "."), dummy))
            state += 1
    return state


def _build_ip_parser_full(n):
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(n + 1)]
    dummy = n
    T = []
    s = _emit_literal(T, curr, 0, "srcip:", dummy)
    s = _emit_ipv4_octets(T, curr, s, reg_vars, dummy, n, "store")
    s = _emit_literal(T, curr, s, " prt:", dummy)
    s = _emit_one_or_more(T, curr, s, NUM, dummy)
    s = _emit_literal(T, curr, s, " dstip:", dummy)
    s = _emit_ipv4_octets(T, curr, s, reg_vars, dummy, n, "check")
    s = _emit_literal(T, curr, s, " prt:", dummy)
    s = _emit_one_or_more(T, curr, s, NUM, dummy)
    s = _emit_literal(T, curr, s, " pload:", dummy)
    T.append(_store(curr, s, s + 1, _eq(curr, "'"), dummy)); s += 1
    s = _emit_one_or_more(T, curr, s, ALPHA_NUM, dummy)
    T.append(_store(curr, s, s + 1, _eq(curr, "'"), dummy)); s += 1
    return RegisterAutomata(s + 1, T, reg_vars, [s])


def _build_ip_parser_simplified(n):
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(n + 1)]
    dummy = n
    T = []
    s = _emit_literal(T, curr, 0, "s:", dummy)
    s = _emit_ipv4_octets(T, curr, s, reg_vars, dummy, n, "store")
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    _emit_zero_or_more(T, curr, s, COLON_OR_ALNUM, dummy)
    s = _emit_literal(T, curr, s, " d:", dummy)
    s = _emit_ipv4_octets(T, curr, s, reg_vars, dummy, n, "check")
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    _emit_zero_or_more(T, curr, s, COLON_OR_ALNUM, dummy)
    s = _emit_literal(T, curr, s, " p:", dummy)
    T.append(_store(curr, s, s + 1, _eq(curr, "'"), dummy)); s += 1
    s = _emit_one_or_more(T, curr, s, ALPHA_NUM, dummy)
    T.append(_store(curr, s, s + 1, _eq(curr, "'"), dummy)); s += 1
    return RegisterAutomata(s + 1, T, reg_vars, [s])


