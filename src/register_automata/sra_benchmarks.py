def export_all(output_dir):
    """Write every automaton in ALL_BUILDERS to `<output_dir>/<name>.json`
    using RegisterAutomata.save_to_json's existing AlphabetRegisterAutomata
    schema (states / transitions / register_vars / final_states)."""
    os.makedirs(output_dir, exist_ok=True)
    for name, builder in ALL_BUILDERS.items():
        builder().save_to_json(os.path.join(output_dir, f"{name}.json"))


