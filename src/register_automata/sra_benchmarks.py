def get_small_ip3_packet_parser_sra():
    """Port of getSmallIP3PacketParserSRA: a minimal one-off demo --
    single (dot-less) 3-digit octet, 's:'/' d:' prefixes, a ' p:' numeric
    port and no payload field at all. Not part of the n-parametrized family."""
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(4)]
    dummy = 3
    T = []
    s = _emit_literal(T, curr, 0, "s:", dummy)
    for i in range(3):
        T.append(_store(curr, s, s + 1, NUM(curr), i))
        s += 1
    s = _emit_literal(T, curr, s, " p:", dummy)
    s = _emit_one_or_more(T, curr, s, NUM, dummy)
    s = _emit_literal(T, curr, s, " d:", dummy)
    for i in range(3):
        T.append(_check(curr, s, s + 1, NUM(curr), i, reg_vars))
        s += 1
    return RegisterAutomata(s + 1, T, reg_vars, [s])


