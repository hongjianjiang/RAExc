"""
Port of the Symbolic Register Automata (SRA) benchmark suite from
lorisdanto/symbolicautomata (benchmarks/src/main/java/SRA/Experiments.java)
to InterpreteRA's RegisterAutomata (DRA) representation.

The upstream SRA model has exactly two move types:
  - SRAStoreMove(from, to, guard, reg): if the input satisfies `guard`,
    unconditionally overwrite register `reg` with the input and move on.
  - SRACheckMove(from, to, guard, reg): if the input satisfies `guard` AND
    equals the current value of register `reg`, move on (no write).

Both map directly onto a single `Transition`:
  - Store  -> guard = <predicate>,               assignment = {reg: "c"}
  - Check  -> guard = And(<predicate>, curr==r),  assignment = {}

Characters are encoded as their ordinal (ASCII) value, so a run over a
string `s` is `automaton.run([ord(c) for c in s])`.

Every public `get_*` function below corresponds 1:1 to a `get*` method in
the Java source. The ProductParser Cn/CLn family and the IPn/IPn-simplified
family are each generated by a small shared builder (`_build_product_parser`,
`_build_ip_parser_full`, `_build_ip_parser_simplified`) because the Java
methods are byte-for-byte the same template scaled by `n`; the builders were
checked state-by-state against the Java source for n = 2, 3, 4, 6, 9.

Known upstream quirks preserved/noted here (not "fixed"):
  - getProductParserCL9 declares an extra (11th) register for the label
    check but never actually uses it for a check -- both label fields are
    plain stores, identical to C9. Ported faithfully (label_check=False).
  - getIP9PacketParserSRA (full, non-simplified) contains a dead duplicate
    transition: SRACheckMove(41,42,dot,9) immediately followed by
    SRAStoreMove(41,42,dot,9). Register 9 is the dummy/garbage register, so
    the check (curr=='.' AND curr==r9) can never be satisfied and the store
    always fires instead -- it has no behavioral effect. Not reproduced here.
"""

import os

import z3

from register_automata.ra import RegisterAutomata, Transition


# ---------------------------------------------------------------------------
# Character predicate helpers (guards are z3 formulas over a "curr" Real var
# holding the ordinal value of the current input character)
# ---------------------------------------------------------------------------

def _eq(curr, ch):
    return curr == ord(ch)


def _range(curr, lo, hi):
    return z3.And(curr >= ord(lo), curr <= ord(hi))


def UPPER(curr):
    return _range(curr, "A", "Z")


def LOWER(curr):
    return _range(curr, "a", "z")


def ALPHA(curr):
    return z3.Or(UPPER(curr), LOWER(curr))


def NUM(curr):
    return _range(curr, "0", "9")


def ALPHA_NUM(curr):
    return z3.Or(ALPHA(curr), NUM(curr))


def NOT_SPACE(curr):
    return curr != ord(" ")


def COLON_OR_ALNUM(curr):
    return z3.Or(_eq(curr, ":"), ALPHA_NUM(curr))


def to_symbols(s):
    """Encode a Python string as the list of ints `RegisterAutomata.run` expects."""
    return [ord(c) for c in s]


# ---------------------------------------------------------------------------
# Move helpers (Store / Check) and small transition-chain builders
# ---------------------------------------------------------------------------

def _store(curr, frm, to, guard, reg):
    return Transition(curr, frm, guard, {f"r{reg}": "c"}, to)


def _check(curr, frm, to, guard, reg, reg_vars):
    return Transition(curr, frm, z3.And(guard, curr == reg_vars[reg]), {}, to)


def _emit_literal(transitions, curr, state, literal, dummy_reg):
    """One SRAStoreMove per character of `literal`, discarded into dummy_reg."""
    for ch in literal:
        transitions.append(_store(curr, state, state + 1, _eq(curr, ch), dummy_reg))
        state += 1
    return state


def _emit_one_or_more(transitions, curr, state, guard_fn, dummy_reg):
    """guard+ : one mandatory move, then a self-loop."""
    transitions.append(_store(curr, state, state + 1, guard_fn(curr), dummy_reg))
    state += 1
    transitions.append(_store(curr, state, state, guard_fn(curr), dummy_reg))
    return state


def _emit_zero_or_more(transitions, curr, state, guard_fn, dummy_reg):
    """guard* as a plain self-loop (state does not advance)."""
    transitions.append(_store(curr, state, state, guard_fn(curr), dummy_reg))
    return state


