# ---------------------------------------------------------------------------
# ProductParser family: "C:<code> L:<label> D:<descr> C:<code> L:<label> D:<descr> ..."
# Cn checks the n-char code repeats; CLn additionally checks the (1-char)
# label repeats. Verified against the Java source state-by-state for
# n = 2, 3, 4, 6, 9.
# ---------------------------------------------------------------------------

def _build_product_parser(code_length, label_check):
    curr = z3.Real("curr")
    num_regs = code_length + 1 + (1 if label_check else 0)
    reg_vars = [z3.Real(f"r{i}") for i in range(num_regs)]
    dummy = 0
    label_reg = code_length + 1 if label_check else None

    T = []
    s = 0
    T.append(_store(curr, s, s + 1, _eq(curr, "C"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    code_start = s
    for i in range(code_length):
        T.append(_store(curr, s, s + 1, NOT_SPACE(curr), i + 1))
        s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, "L"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    if label_check:
        T.append(_store(curr, s, s + 1, ALPHA_NUM(curr), label_reg)); s += 1
    else:
        T.append(_store(curr, s, s + 1, ALPHA_NUM(curr), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, "D"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    descr_loop_state = s
    s = _emit_one_or_more(T, curr, s, ALPHA, dummy)
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1

    repeat_start = s  # this is where the repeated "C:...L:...D:..." block starts and loops back to
    T.append(_store(curr, s, s + 1, _eq(curr, "C"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    for i in range(code_length):
        T.append(_check(curr, s, s + 1, NOT_SPACE(curr), i + 1, reg_vars))
        s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, "L"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    if label_check:
        T.append(_check(curr, s, s + 1, ALPHA_NUM(curr), label_reg, reg_vars)); s += 1
    else:
        T.append(_store(curr, s, s + 1, ALPHA_NUM(curr), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, " "), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, "D"), dummy)); s += 1
    T.append(_store(curr, s, s + 1, _eq(curr, ":"), dummy)); s += 1
    s = _emit_one_or_more(T, curr, s, ALPHA, dummy)
    # loop the repeated block back on itself via a space transition
    T.append(_store(curr, s, repeat_start, _eq(curr, " "), dummy))

    final_state = s
    return RegisterAutomata(final_state + 1, T, reg_vars, [final_state])


