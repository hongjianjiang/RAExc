    """Port of getSSNParser: checks BOTH repeated initials (3 registers)."""
    curr = z3.Real("curr")
    reg_vars = [z3.Real(f"r{i}") for i in range(3)]
    T = [
        _store(curr, 0, 1, UPPER(curr), 0),
        _store(curr, 1, 1, LOWER(curr), 2),
        _store(curr, 1, 2, _eq(curr, ","), 2),
        _store(curr, 2, 2, _eq(curr, " "), 2),
        _store(curr, 2, 3, UPPER(curr), 1),
        _store(curr, 3, 3, LOWER(curr), 2),
        _store(curr, 3, 4, _eq(curr, ","), 2),
        _store(curr, 4, 4, _eq(curr, " "), 2),
        _check(curr, 4, 5, UPPER(curr), 0, reg_vars),
        _check(curr, 5, 6, UPPER(curr), 1, reg_vars),
    ]
    return RegisterAutomata(7, T, reg_vars, [6])


